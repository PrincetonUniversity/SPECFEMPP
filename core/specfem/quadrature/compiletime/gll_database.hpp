#pragma once

#include <Kokkos_Core.hpp>

// in Python, first, set N = NGLL, and make sure scipy is imported. Then, run:
// clang-format off
// ===================================================================================
// print(-1,*(f"{x:.40}" for x in scipy.special.roots_jacobi(N-2,1,1)[0]),1, sep=", ")
// ===================================================================================
// clang-format on
namespace specfem::quadrature::compiletime {
struct gll_database {
  template <int NGLL> static consteval Kokkos::Array<double, NGLL> nodes() {
    static_assert(NGLL >= 2, "GLL makes no sense with < 2 nodes!");
    if constexpr (NGLL == 2) {
      return { -1, 1 };
    } else if constexpr (NGLL == 3) {
      return { -1, 0.0, 1 };
    } else if constexpr (NGLL == 4) {
      return { -1, -0.4472135954999579277036048097215825691819,
               0.4472135954999579277036048097215825691819, 1 };
    } else if constexpr (NGLL == 5) {
      return { -1, -0.6546536707079770867068191364523954689503, 0.0,
               0.6546536707079770867068191364523954689503, 1 };
    } else if constexpr (NGLL == 6) {
      return { -1,
               -0.7650553239294646257206977679743431508541,
               -0.2852315164806450420442729409842286258936,
               0.2852315164806450420442729409842286258936,
               0.7650553239294646257206977679743431508541,
               1 };
    } else if constexpr (NGLL == 7) {
      return { -1,
               -0.8302238962785670750577082799281924962997,
               -0.4688487934707141757684212279855273663998,
               0.0,
               0.4688487934707141757684212279855273663998,
               0.8302238962785670750577082799281924962997,
               1 };
    } else if constexpr (NGLL == 8) {
      return { -1,
               -0.8717401485096065716362545572337694466114,
               -0.5917001814331424025539263311657123267651,
               -0.2092992179024789067831591182766715064645,
               0.2092992179024789067831591182766715064645,
               0.5917001814331424025539263311657123267651,
               0.8717401485096065716362545572337694466114,
               1 };
    } else if constexpr (NGLL == 9) {
      return { -1,
               -0.8997579954114602873715966779855079948902,
               -0.6771862795107377319681063454481773078442,
               -0.3631174638261781550951923236425500363111,
               0.0,
               0.3631174638261781550951923236425500363111,
               0.6771862795107377319681063454481773078442,
               0.8997579954114602873715966779855079948902,
               1 };
    } else if constexpr (NGLL == 10) {
      return { -1,
               -0.9195339081664588576359165017493069171906,
               -0.7387738651055050231875043209583964198828,
               -0.4779249498104445326163158824783749878407,
               -0.1652789576663870330097694250071072019637,
               0.1652789576663870330097694250071072019637,
               0.4779249498104445326163158824783749878407,
               0.7387738651055050231875043209583964198828,
               0.9195339081664588576359165017493069171906,
               1 };
    } else {
      // fail here, but don't static_assert(false), since some compilers bypass
      // the if-constexpr.
      static_assert(NGLL != 0, "specfem::quadrature::compiletime::gll_database:"
                               ":nodes not set for this NGLL value!");
    }
  }
};

} // namespace specfem::quadrature::compiletime
