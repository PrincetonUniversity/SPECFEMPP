#!/usr/bin/env python3
"""Detect an Intel GPU, validate AOT compilation, and create local CMake presets."""

import argparse
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile


PRESET_NAME = "release-sycl-aot"


def detect_devices(pci_root=Path("/sys/bus/pci/devices")):
    """Return Intel display-controller PCI IDs without requiring a GPU runtime."""
    devices = {}
    for path in sorted(pci_root.glob("*")):
        try:
            vendor = int((path / "vendor").read_text().strip(), 16)
            device_class = int((path / "class").read_text().strip(), 16)
            device = int((path / "device").read_text().strip(), 16)
        except (OSError, ValueError):
            continue
        if vendor == 0x8086 and device_class >> 16 == 0x03:
            devices.setdefault(f"0x{device:04x}", []).append(path.name)
    return devices


def normalize_device(value):
    if not re.fullmatch(r"(?:0x)?[0-9a-fA-F]{4}", value):
        raise ValueError("Device must be a four-digit PCI ID, such as 0x7d51.")
    return f"0x{int(value, 16):04x}"


def select_device(explicit_device=None, pci_root=Path("/sys/bus/pci/devices")):
    if explicit_device:
        return normalize_device(explicit_device)
    devices = detect_devices(pci_root)
    if not devices:
        raise ValueError(
            "No Intel GPU detected through Linux PCI sysfs. "
            "For cross-compilation or other operating systems, use --device <PCI-ID>."
        )
    if len(devices) > 1:
        choices = ", ".join(
            f"{device} ({', '.join(addresses)})"
            for device, addresses in devices.items()
        )
        raise ValueError(
            f"Multiple Intel GPU types detected: {choices}. "
            "Select one with --device <PCI-ID>."
        )
    return next(iter(devices))


def aot_flags(device):
    return [
        "-fsycl",
        "-fsycl-targets=spir64_gen",
        "-Xsycl-target-backend=spir64_gen",
        f"-device {device}",
    ]


def validate_compiler(compiler, device):
    """Compile a real device kernel; do not require execution on the target GPU."""
    with tempfile.TemporaryDirectory(prefix="specfem-sycl-aot-") as directory:
        source = Path(directory) / "check.cpp"
        source.write_text(
            "#include <sycl/sycl.hpp>\n"
            "int main() {\n"
            "  sycl::queue q;\n"
            "  int *p = sycl::malloc_shared<int>(1, q);\n"
            "  q.single_task([=]() { *p = 42; }).wait();\n"
            "  sycl::free(p, q);\n"
            "}\n"
        )
        command = [compiler, "-fno-sycl-rdc", *aot_flags(device)]
        command += [str(source), "-o", str(Path(directory) / "check")]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            raise ValueError(
                f"AOT compilation failed for {device}; no presets were changed.\n"
                "Ensure the Intel compiler and ocloc support this GPU.\n"
                + result.stdout
                + result.stderr
            )
        print(result.stdout + result.stderr, end="")


def update_presets(path, device, compiler):
    """Merge the generated entries while preserving unrelated user configuration."""
    data = json.loads(path.read_text()) if path.exists() else {"version": 6}
    data["version"] = max(data.get("version", 6), 6)
    configure = {
        "name": PRESET_NAME,
        "displayName": f"Release -- SYCL AOT for Intel GPU {device}",
        "description": "Generated by scripts/setup_sycl_aot.py for the selected GPU.",
        "inherits": "release-sycl",
        "binaryDir": "${sourceDir}/build/release-sycl-aot",
        "cacheVariables": {
            "CMAKE_CXX_COMPILER": compiler,
            # These flags also apply to project() compiler checks, before Kokkos.
            "CMAKE_CXX_FLAGS": " ".join(
                f'"{flag}"' if " " in flag else flag for flag in aot_flags(device)
            ),
            "CMAKE_INSTALL_PREFIX": "${sourceDir}/bin/release-sycl-aot",
            "SPECFEM_BENCHMARKS_BUILD_DIR": (
                "${sourceDir}/benchmarks/build/release-sycl-aot"
            ),
        },
    }
    build = {
        "name": PRESET_NAME,
        "configurePreset": PRESET_NAME,
        "targets": ["all"],
    }
    for section, generated in [
        ("configurePresets", configure),
        ("buildPresets", build),
    ]:
        presets = data.setdefault(section, [])
        existing = next((p for p in presets if p["name"] == PRESET_NAME), None)
        if existing is None:
            presets.append(generated)
        else:
            if section == "configurePresets":
                generated["cacheVariables"] = {
                    **existing.get("cacheVariables", {}),
                    **generated["cacheVariables"],
                }
            existing.update(generated)
    # Replace atomically so an interrupted write cannot truncate existing presets.
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(json.dumps(data, indent=2) + "\n")
            stream.close()
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--device", help="Target PCI device ID; default: detect local GPU"
    )
    parser.add_argument("--compiler", default="icpx", help="Intel compiler executable")
    parser.add_argument(
        "--configure",
        action="store_true",
        help="Also run CMake configure after validation",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    try:
        device = select_device(args.device)
        compiler = shutil.which(args.compiler)
        if compiler is None:
            raise ValueError(
                f"Compiler {args.compiler!r} not found. Load your Intel oneAPI "
                "environment or pass --compiler /path/to/icpx."
            )
        print(f"Selected Intel GPU PCI device {device}. Validating AOT compilation...")
        validate_compiler(compiler, device)
        update_presets(root / "CMakeUserPresets.json", device, compiler)
        print(f"Updated local preset {PRESET_NAME} in CMakeUserPresets.json.")
        configure_command = ["cmake", "--preset", PRESET_NAME]
        if args.configure:
            subprocess.run(configure_command, cwd=root, check=True)
        else:
            print(shlex.join(configure_command))
        print(f"cmake --build --preset {PRESET_NAME} --parallel 4")
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
